// Worker: Get own attendance history
export const getUserAttendanceHistory = async (userId: string): Promise<AttendanceRecord[]> => {
  const q = query(collection(db, 'attendance'), where('userId', '==', userId));
  const snap = await getDocs(q);
  const records = snap.docs.map(doc => doc.data() as AttendanceRecord);
  // Sort in descending order by date in JavaScript to avoid Firestore composite index requirement
  return records.sort((a, b) => b.date.localeCompare(a.date));
};

// Worker: Get own tasks
export const getUserTasks = async (userId: string) => {
  const q = query(collection(db, 'tasks'), where('userId', '==', userId));
  const snap = await getDocs(q);
  const tasks = snap.docs.map(doc => ({ id: doc.id, ...doc.data() as any }));
  // Sort in descending order by createdAt
  return tasks.sort((a, b) => {
    const timeA = a.createdAt?.toMillis ? a.createdAt.toMillis() : 0;
    const timeB = b.createdAt?.toMillis ? b.createdAt.toMillis() : 0;
    return timeB - timeA;
  });
};

// --- HOLIDAY & AUTO-LEAVE SYSTEM ---

export const markHoliday = async (date: string, description: string) => {
  const docRef = doc(db, 'holidays', date);
  await setDoc(docRef, { date, description, createdAt: serverTimestamp() });
};

export const getHolidays = async (): Promise<string[]> => {
  const snap = await getDocs(collection(db, 'holidays'));
  return snap.docs.map(doc => doc.id); // Returns array of date strings 'YYYY-MM-DD'
};

export const fillMissingLeaves = async (userId: string) => {
  // 1. Get user to find their start date
  const userRef = doc(db, 'users', userId);
  const userSnap = await getDoc(userRef);
  if (!userSnap.exists()) return;
  const userData = userSnap.data();
  if (!userData.createdAt) return;

  const startDate = userData.createdAt.toDate();
  const today = new Date();
  today.setHours(0, 0, 0, 0);

  // 2. Get all existing attendances for user
  const attendanceHistory = await getUserAttendanceHistory(userId);
  const existingDates = new Set(attendanceHistory.map(a => a.date));

  // 3. Get all holidays
  const holidays = await getHolidays();
  const holidaySet = new Set(holidays);

  // 4. Iterate from start date to yesterday
  let currentDate = new Date(startDate);
  currentDate.setHours(0, 0, 0, 0);

  const batchPromises = [];

  while (currentDate < today) {
    const dateStr = currentDate.toISOString().split('T')[0];
    const isSunday = currentDate.getDay() === 0;

    // If not a Sunday, not a Holiday, and no attendance record exists, mark as Leave
    if (!isSunday && !holidaySet.has(dateStr) && !existingDates.has(dateStr)) {
      const docRef = doc(db, 'attendance', `${userId}_${dateStr}`);
      batchPromises.push(
        setDoc(docRef, {
          userId,
          date: dateStr,
          status: 'leave',
          autoGenerated: true,
          appliedAt: serverTimestamp()
        })
      );
    }
    currentDate.setDate(currentDate.getDate() + 1);
  }

  // Execute all creations
  if (batchPromises.length > 0) {
    await Promise.all(batchPromises);
  }
};

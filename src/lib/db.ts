import { db } from './firebase';
import { 
  collection, doc, getDoc, getDocs, setDoc, updateDoc, 
  query, where, orderBy, serverTimestamp, addDoc, Timestamp 
} from 'firebase/firestore';
import { AppUser } from './auth';

export interface AttendanceRecord {
  id?: string;
  userId: string;
  date: string; // YYYY-MM-DD
  punchIn: any; // Timestamp
  punchOut: any | null; // Timestamp
  totalHours: number;
  overtimeHours: number;
  status: 'present' | 'leave' | 'half-day';
  autoGenerated?: boolean; // To identify if it was auto-filled
}

// Get current date string in YYYY-MM-DD format
export const getTodayDateString = () => {
  const today = new Date();
  return today.toISOString().split('T')[0];
};

// Check if user has punched in today
export const getTodayAttendance = async (userId: string): Promise<AttendanceRecord | null> => {
  const dateStr = getTodayDateString();
  const docRef = doc(db, 'attendance', `${userId}_${dateStr}`);
  const snap = await getDoc(docRef);
  if (snap.exists()) {
    return { id: snap.id, ...snap.data() } as AttendanceRecord;
  }
  return null;
};

// Punch In
export const punchIn = async (userId: string) => {
  const dateStr = getTodayDateString();
  const docRef = doc(db, 'attendance', `${userId}_${dateStr}`);
  
  const record: AttendanceRecord = {
    userId,
    date: dateStr,
    punchIn: serverTimestamp(),
    punchOut: null,
    totalHours: 0,
    overtimeHours: 0,
    status: 'present'
  };

  await setDoc(docRef, record);
};

// Punch Out and Calculate Hours
export const punchOut = async (userId: string) => {
  const dateStr = getTodayDateString();
  const docRef = doc(db, 'attendance', `${userId}_${dateStr}`);
  const snap = await getDoc(docRef);
  
  if (!snap.exists()) throw new Error("No punch in record found for today.");
  
  const data = snap.data() as AttendanceRecord;
  if (data.punchOut) throw new Error("Already punched out.");

  const punchInTime = (data.punchIn as Timestamp).toDate().getTime();
  const punchOutDate = new Date();
  const punchOutTime = punchOutDate.getTime();
  
  const totalMs = punchOutTime - punchInTime;
  const totalHours = totalMs / (1000 * 60 * 60);
  
  // Standard shift is 9 hours
  let overtimeHours = 0;
  if (totalHours > 9) {
    overtimeHours = totalHours - 9;
  }

  // Calculate status based on local punch out hour
  // Shift is 9 AM to 6 PM (18:00)
  // Left before 6 PM and after 1 PM -> half-day
  // Left before 1 PM -> leave
  const punchOutHour = punchOutDate.getHours();
  let status: 'present' | 'leave' | 'half-day' = 'present';

  if (punchOutHour < 18) {
    if (punchOutHour >= 13) {
      status = 'half-day';
    } else {
      status = 'leave';
    }
  }

  await updateDoc(docRef, {
    punchOut: serverTimestamp(),
    totalHours,
    overtimeHours,
    status
  });
};

